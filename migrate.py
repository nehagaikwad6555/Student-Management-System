import os
import sqlite3
import psycopg2
from dotenv import load_dotenv

load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")
SOURCE_DB = "student_management.db"

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL missing in .env")

if not os.path.exists(SOURCE_DB):
    raise FileNotFoundError(
        f"{SOURCE_DB} not found. Check your SQLite database filename."
    )

old_db = sqlite3.connect(SOURCE_DB)
old_db.row_factory = sqlite3.Row

new_db = psycopg2.connect(DATABASE_URL)

try:
    with new_db.cursor() as cur:
        cur.execute("""
            CREATE TABLE IF NOT EXISTS students (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                email TEXT,
                phone TEXT,
                course TEXT,
                department TEXT
            )
        """)

        students = old_db.execute(
            "SELECT id, name, email, phone, course, department FROM students"
        ).fetchall()

        for s in students:
            cur.execute("""
                INSERT INTO students
                (id, name, email, phone, course, department)
                VALUES (%s, %s, %s, %s, %s, %s)
                ON CONFLICT (id) DO NOTHING
            """, (
                s["id"], s["name"], s["email"], s["phone"],
                s["course"], s["department"]
            ))

        cur.execute("""
            SELECT setval(
                pg_get_serial_sequence('students', 'id'),
                COALESCE((SELECT MAX(id) FROM students), 1),
                EXISTS (SELECT 1 FROM students)
            )
        """)

    new_db.commit()
    print(f"Migration complete. Source records found: {len(students)}")

finally:
    old_db.close()
    new_db.close()